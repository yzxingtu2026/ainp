#!/bin/sh
# Build pinned MuPDF with CJK fonts for go-fitz extlib.
# Usage: build-mupdf-cjk.sh [prefix]
# Headers and libraries must come from the same MuPDF version.
set -eu

PREFIX="${1:-/usr/local}"
MUPDF_VERSION="${MUPDF_VERSION:-1.28.2}"
MUPDF_SHA256="${MUPDF_SHA256:-44075a84e329db55b9bef5f342a70fd26d69e48ad1d33cb89d9664581c641156}"
MUPDF_URL="${MUPDF_URL:-https://mupdf.com/downloads/archive/mupdf-${MUPDF_VERSION}-source.tar.gz}"
JOBS="${MUPDF_JOBS:-$(getconf _NPROCESSORS_ONLN 2>/dev/null || echo 2)}"

workdir="${TMPDIR:-/tmp}/ainp-mupdf-$$"
mkdir -p "$workdir"
trap 'rm -rf "$workdir"' EXIT

archive="$workdir/mupdf-source.tar.gz"
echo "downloading MuPDF ${MUPDF_VERSION}"
curl -fsSL "$MUPDF_URL" -o "$archive"
actual="$(sha256sum "$archive" | awk '{print $1}')"
if [ "$actual" != "$MUPDF_SHA256" ]; then
	echo "MuPDF checksum mismatch: got $actual want $MUPDF_SHA256" >&2
	exit 1
fi

tar -xzf "$archive" -C "$workdir"
src="$(find "$workdir" -mindepth 1 -maxdepth 1 -type d -name 'mupdf-*-source' | head -n 1)"
if [ -z "$src" ]; then
	echo "MuPDF source directory not found" >&2
	exit 1
fi

# Official source includes CJK fonts. Do not set TOFU or TOFU_CJK.
make -C "$src" \
	prefix="$PREFIX" \
	HAVE_X11=no \
	HAVE_GLUT=no \
	HAVE_CURL=no \
	shared=no \
	build=release \
	-j"$JOBS"
make -C "$src" \
	prefix="$PREFIX" \
	HAVE_X11=no \
	HAVE_GLUT=no \
	HAVE_CURL=no \
	shared=no \
	build=release \
	install

version_h="$PREFIX/include/mupdf/fitz/version.h"
if ! grep -q "FZ_VERSION \"${MUPDF_VERSION}\"" "$version_h"; then
	echo "installed MuPDF headers are not ${MUPDF_VERSION}: $version_h" >&2
	cat "$version_h" >&2
	exit 1
fi
if [ ! -f "$PREFIX/lib/libmupdf.a" ]; then
	echo "libmupdf.a was not installed" >&2
	exit 1
fi
# go-fitz -tags static expects -lmupdf-third. Newer MuPDF folds third-party into libmupdf.a.
if [ ! -f "$PREFIX/lib/libmupdf-third.a" ]; then
	ar rcs "$PREFIX/lib/libmupdf-third.a"
fi

mkdir -p "$PREFIX/share"
cat >"$PREFIX/share/ainp-mupdf-cgo.env" <<EOF
# Generated by docker/build-mupdf-cjk.sh
export CGO_ENABLED=1
export CGO_CFLAGS="-I${PREFIX}/include"
export CGO_LDFLAGS="-L${PREFIX}/lib -lmupdf -lmupdf-third -lm"
EOF

echo "MuPDF ${MUPDF_VERSION} installed to ${PREFIX} with CJK fonts"
