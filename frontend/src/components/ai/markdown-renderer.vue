<script setup lang="ts">
import { computed, onBeforeUnmount } from 'vue';
import DOMPurify from 'dompurify';
import { Marked, Renderer, type Tokens } from 'marked';
import { $t } from '@/locales';
import { copyPlainText } from './clipboard';

defineOptions({ name: 'MarkdownRenderer' });

const props = withDefaults(
  defineProps<{
    content: string;
    streaming?: boolean;
  }>(),
  {
    streaming: false
  }
);

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function normalizeCodeLang(lang?: string): string {
  const token = (lang || '').trim().split(/\s+/)[0] || '';
  return token.replace(/[^a-zA-Z0-9_+#.-]/g, '').toLowerCase();
}

const copyTimers = new Map<HTMLButtonElement, number>();

onBeforeUnmount(() => {
  for (const timer of copyTimers.values()) {
    window.clearTimeout(timer);
  }
  copyTimers.clear();
});

const html = computed(() => {
  const copyText = escapeHtml($t('chat.copy'));
  const copyAria = escapeHtml($t('chat.copyCode'));
  const fallbackLang = escapeHtml($t('chat.codeLanguage'));
  const baseRenderer = new Renderer();
  const markdown = new Marked({
    gfm: true,
    breaks: true,
    renderer: {
      code({ text, lang }: Tokens.Code) {
        const safeLang = normalizeCodeLang(lang);
        const langLabel = safeLang ? escapeHtml(safeLang) : fallbackLang;
        const langClass = safeLang ? ` class="language-${escapeHtml(safeLang)}"` : '';
        const escapedCode = escapeHtml(text);
        return (
          `<div class="md-code-block">` +
          `<div class="md-code-block__header">` +
          `<span class="md-code-block__meta">` +
          `<span class="md-code-block__dots" aria-hidden="true"><i></i><i></i><i></i></span>` +
          `<span class="md-code-block__lang">${langLabel}</span>` +
          `</span>` +
          `<button type="button" class="md-code-block__copy" data-md-copy="true" aria-label="${copyAria}">` +
          `<span class="md-code-block__copy-label">${copyText}</span>` +
          `</button>` +
          `</div>` +
          `<pre class="md-code-block__pre"><code${langClass}>${escapedCode}</code></pre>` +
          `</div>\n`
        );
      },
      table(token: Tokens.Table) {
        return `<div class="md-table-wrap">${baseRenderer.table.call(this, token)}</div>\n`;
      }
    }
  });

  const rendered = markdown.parse(props.content, { async: false }) as string;

  return DOMPurify.sanitize(rendered, {
    FORBID_TAGS: ['form', 'iframe', 'img', 'style'],
    FORBID_ATTR: ['style']
  });
});

async function onContainerClick(event: MouseEvent) {
  const target = event.target instanceof Element ? event.target : null;
  const button = target?.closest('button[data-md-copy="true"]');
  if (!(button instanceof HTMLButtonElement)) return;
  const codeElement = button.closest('.md-code-block')?.querySelector('pre code');
  const rawCode = codeElement?.textContent ?? '';
  if (!rawCode) return;

  const copied = await copyPlainText(rawCode);
  if (!copied) return;

  const label = button.querySelector('.md-code-block__copy-label');
  button.dataset.copied = 'true';
  if (label) label.textContent = $t('chat.copied');

  const existing = copyTimers.get(button);
  if (existing !== undefined) window.clearTimeout(existing);
  const timer = window.setTimeout(() => {
    button.removeAttribute('data-copied');
    if (label) label.textContent = $t('chat.copy');
    copyTimers.delete(button);
  }, 1800);
  copyTimers.set(button, timer);
}
</script>

<template>
  <!-- HTML is generated by marked and sanitized with DOMPurify above. -->
  <!-- eslint-disable vue/no-v-html -->
  <div
    class="markdown-renderer break-words"
    :class="{ 'markdown-renderer--streaming': streaming }"
    @click="onContainerClick"
    v-html="html"
  />
  <!-- eslint-enable vue/no-v-html -->
</template>

